import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
const source=readFileSync('cloudflare/workers/jarvis-backend.mjs','utf8');
const sha=s=>createHash('sha256').update(s).digest('hex');
const known='8d1d6287b097794850bb1a1832e9dba7a3568a9ddf0d4813175c421ed0fb1430';
assert.equal(sha(source),known,'Candidate backend source must match the independently verified GitHub provenance manifest');
const html=readFileSync('cloudflare/ui/command-v4-unified.html','utf8');
const manifest=readFileSync('cloudflare/ui/jarvis-app.webmanifest','utf8');
assert(html.includes('id="importLocalWorkspace"'));
assert(html.includes("credentials:'same-origin'"),'Cloud APIs must remain same-origin authenticated');
assert(html.includes("if(STATIC_PREVIEW)throw Error"),'No GitHub Pages writes allowed');
const anchor='if (path === "/jarvis" && method === "GET")';
assert.equal(source.split(anchor).length,2,'Legacy route must be unique and retained');
const headers={"Content-Type":"text/html; charset=utf-8","Cache-Control":"no-store","X-Content-Type-Options":"nosniff","Content-Security-Policy":"default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'self'; img-src 'self' data:; base-uri 'none'; frame-ancestors 'none'; form-action 'self'"};
const htmlRoute='if(path==="/jarvis-unified"&&method==="GET")return new Response('+JSON.stringify(html)+',{headers:'+JSON.stringify(headers)+'});\n    ';
const manifestRoute='if(path==="/jarvis-app.webmanifest"&&method==="GET")return new Response('+JSON.stringify(manifest)+',{headers:{"Content-Type":"application/manifest+json; charset=utf-8","Cache-Control":"no-store","X-Content-Type-Options":"nosniff"}});\n    ';
const candidate=source.replace(anchor,htmlRoute+manifestRoute+anchor);
assert(candidate.includes(anchor),'Existing application route must remain unchanged');
mkdirSync('dist',{recursive:true});
writeFileSync('dist/jarvis-backend-unified-candidate.mjs',candidate);
console.log('Unified app is a BUILD-ONLY production candidate, NOT deployed; source sha256 '+sha(candidate));
