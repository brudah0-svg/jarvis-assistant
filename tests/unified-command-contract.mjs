import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';

// Build-only synthetic contract. No D1 binding, auth token, or live Cloudflare requests.
execFileSync(process.execPath, ['scripts/build-unified.mjs'], {stdio:'inherit'});
execFileSync(process.execPath, ['--check','dist/jarvis-backend.mjs'], {stdio:'inherit'});
const worker=(await import(pathToFileURL(resolve('dist/jarvis-backend.mjs')).href)).default;
const source=readFileSync('cloudflare/workers/jarvis-backend.mjs','utf8');
const original=readFileSync('dist/jarvis-backend.mjs','utf8');
const ui=readFileSync('cloudflare/ui/command-v4.html','utf8');
assert(source.includes('async fetch(request, env, ctx)'),'original Worker entry must remain');
assert(original.length>source.length+ui.length/2,'generated artifact must include embedded UI');
const endpoint='https://jarvis.example/command-v4';
const context={waitUntil:()=>{}};
const res=await worker.fetch(new Request(endpoint),{},context);
assert.equal(res.status,200);
assert.equal(res.headers.get('content-type'),'text/html; charset=utf-8');
assert.match(res.headers.get('cache-control'),/no-store/);
assert.match(res.headers.get('content-security-policy'),/connect-src 'self'/);
const page=await res.text();
assert(page.includes('JARVIS CLOUD · MODALITÀ AVANZATA'));
assert(page.includes('/api/projects'));
assert(page.includes('/api/tasks'));
assert(page.includes('/api/memory'));
assert(page.includes('/api/ai-chat'));
assert(page.includes('/planner-v3'));
assert(page.includes('/executor-v3'));
assert(page.includes('/self-improvement-v3'));
assert(page.includes('/autonomy-control-v3'));
assert(page.includes('/sandbox-v3'));
assert(page.includes('/recovery-download-v3'));
assert(!page.includes('localStorage.'),'Cloud UI must not touch legacy phone storage');
assert(!page.includes('src="app.js"'),'Cloud UI must be self-contained');
const cross=await worker.fetch(new Request(endpoint,{headers:{Origin:'https://untrusted.example'}}),{},context);
assert.equal(cross.status,403,'disallow untrusted origins');
const passthrough=await worker.fetch(new Request('https://jarvis.example/api/executor/tools'),{},context);
const response=await passthrough.json();
assert.equal(passthrough.status,200,'backend API must remain available');
assert.equal(response.mode,'diagnostics_only');
assert.equal(response.tools.length,5);
assert.equal(response.approval_required_for_writes,true);
const missing=await worker.fetch(new Request('https://jarvis.example/not-a-route'),{},context);
assert.equal(missing.status,404);
console.log('Unified command checks passed: protected same-origin interface, API passthrough, modules and local data isolation.');
