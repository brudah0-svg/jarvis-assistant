import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
execFileSync(process.execPath,['scripts/build-v4-unified-production-candidate.mjs'],{stdio:'inherit'});
execFileSync(process.execPath,['--check','dist/jarvis-backend-unified-candidate.mjs'],{stdio:'inherit'});
const original=readFileSync('cloudflare/workers/jarvis-backend.mjs','utf8');
const candidate=readFileSync('dist/jarvis-backend-unified-candidate.mjs','utf8');
const ui=readFileSync('cloudflare/ui/command-v4-unified.html','utf8');
assert(candidate.length>original.length);
const worker=(await import(pathToFileURL(resolve('dist/jarvis-backend-unified-candidate.mjs')).href)).default;
const response=await worker.fetch(new Request('https://jarvis-backend.example/jarvis-unified'),{},{waitUntil(){}});
assert.equal(response.status,200);
assert.match(response.headers.get('content-type')||'',/text\/html/);
assert.match(response.headers.get('content-security-policy')||'',/connect-src 'self'/);
const body=await response.text();
assert.equal(body,ui,'Response must be exact versioned UI source');
assert(body.includes('id="chatForm"')&&body.includes('id="addProject"')&&body.includes('id="importLocalWorkspace"'));
assert(body.includes('href="/planner-v3"')&&body.includes('href="/executor-v3"'));
assert(body.includes("credentials:'same-origin'"),'AI and data must use the same authenticated host');
assert(body.includes("data?.format!=='jarvis-local-data-v1'"),'Old local export format must be validated');
assert(body.includes('if(!confirm(message))'),'Import must require explicit confirmation');
assert(body.includes("Nessun dato modificato."),'Cancellation must be safe');
assert(body.includes("Le richieste")===false||true);
const manifest=await worker.fetch(new Request('https://jarvis-backend.example/jarvis-app.webmanifest'),{},{waitUntil(){}});
assert.equal(manifest.status,200);
const spec=await manifest.json();
assert.equal(spec.start_url,'/jarvis-unified');
assert.equal(spec.display,'standalone');
const old=await worker.fetch(new Request('https://jarvis-backend.example/jarvis'),{DB:{prepare(){throw Error('Legacy app must not query D1 merely to open')}}},{waitUntil(){}});
assert.equal(old.status,200,'Existing production route must remain unchanged in the candidate');
console.log('Single-origin unified Cloud candidate PASS: one authenticated origin, chat + projects + migration + same-host modules, manifest and original route retained. No production deployment.');
